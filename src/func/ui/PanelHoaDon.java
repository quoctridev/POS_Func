    void init() {
        model = (DefaultTableModel) tblDanhSach.getModel();
        model.setRowCount(0);
        int i = 1;
        ls = new BillDAO().selectAll();
        for (BillDTO bill : ls) {
            LocalDateTime time = bill.getOrderDate().toLocalDateTime();
            model.addRow(new Object[]{
                i, bill.getCustomerName() == null ? "Khách vãng lai" : bill.getCustomerName(), bill.getCustomerPhone() == null ? "Không có" : bill.getCustomerPhone(), bill.getNumberTable(), Currency.formatVND(bill.getTotal_price()), bill.getStatus(), time.format(formatter)});
            i++;
        }
        SuKienHanhDong event = new SuKienHanhDong() {
            @Override
            public void Edit(int row) {
                Message.warning(null, "Chưa có tính năng");
                return;
            }

            @Override
            public void Delete(int row) {
                Message.warning(null, "Chưa có tính năng");
                return;
            }

            @Override
            public void View(int row) {
                DialogChiTietHoaDon donHang = new DialogChiTietHoaDon((Frame) SwingUtilities.getWindowAncestor(PanelHoaDon.this), true);
                donHang.setBill(ls.get(row));
                donHang.setVisible(true);
            }

        };

        tblDanhSach.getColumnModel().getColumn(7).setCellRenderer(new KetHopBang(true));
        tblDanhSach.getColumnModel().getColumn(7).setCellEditor(new ChinhSuaBang(true, event));
        tblDanhSach.getColumnModel().getColumn(7).setMinWidth(95);
        tblDanhSach.getColumnModel().getColumn(7).setMaxWidth(95);
        tblDanhSach.getColumnModel().getColumn(7).setWidth(95);
    }

