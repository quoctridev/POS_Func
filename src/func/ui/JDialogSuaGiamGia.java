    private void HienThi() {
        if (discount != null) {
        txtMaCode.setText(discount.getCode()); // Hiển thị mã giảm giá
        txtKetThuc.setText(discount.getEndDate().toString()); // Hiển thị ngày kết thúc
        txtGiamGia.setText(discount.getDiscountValue().toString()); // Hiển thị giá trị giảm giá

        // Hiển thị tình trạng
        if (discount.getEndDate().before(new Date())) {
            rboHetHan.setSelected(true); // Hết hạn
        } else {
            rboConHieuLuc.setSelected(true); // Còn hiệu lực
        }
    }
}


