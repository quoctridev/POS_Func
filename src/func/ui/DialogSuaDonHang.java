    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String luaChon = String.valueOf(cboTrangThai.getSelectedItem());
        switch (luaChon) {
            case "Đang chờ":
                luaChon = "pending";
                break;
            case "Đang nấu":
                luaChon = "cooking";
                break;
            case "Đã hoàn thành":
                luaChon = "ready";
                break;
            case "Huỷ":
                luaChon = "canceled";
                break;
        }
        OrderOrderDetailDTO order = new OrderOrderDetailDTO();
        order.setStatus(luaChon);
        order.setOrderDetailId(orderDetail.getOrderDetailId());
        if (luaChon.equals("canceled")) {
            String note = Message.input(null, "Lí do huỷ của món này là gì");
            OrderOrderDetailDAO.updateStatusById(order, note);
        }
        OrderOrderDetailDAO.updateStatusById(order, null);
        dispose();
    }//GEN-LAST:event_jButton1ActionPerformed

