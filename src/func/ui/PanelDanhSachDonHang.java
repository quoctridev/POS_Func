    void init() {
        lblBan.setText("");
        lblKhuVuc.setText("");
        lblThoiGian.setText("");
        lblThuNgan.setText("");
        DefaultTableModel model = (DefaultTableModel) tableDanhSach.getModel();
        model.setRowCount(0);
        List<OrderOrderDetailDTO> orders = OrderOrderDetailDAO.loadAllOrdersToTable();
        for (OrderOrderDetailDTO order : orders) {
            String trangThai;
            switch (order.getStatus()) {
                case "pending":
                    trangThai = "Đang Chờ";
                    break;
                case "processing":
                    trangThai = "Đang Xử Lý";
                    break;
                case "cooking":
                    trangThai = "Đang Chế Biến";
                    break;
                case "completed":
                    trangThai = "Đã Hoàn Thành";
                    break;
                case "canceled":
                    trangThai = "Hủy";
                    break;
                default:
                    trangThai = "Không Xác Định";
                    break;
                
            }
            
            model.addRow(new Object[]{
                order.getOrderId(),
                order.getOrderDate(),
                order.getCashierName(),
                order.getZone(),
                order.getTableNumber(),
                trangThai,
                order.getNote()
            });
        }
        
    }
    
    void refreshTable() {
        Timer time = new Timer(10000, new ActionListener() {
            
            @Override
            public void actionPerformed(ActionEvent e) {
                init();
            }
        }
        );
        time.start();
    }

