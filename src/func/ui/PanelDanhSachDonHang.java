    private void tableDanhSachMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tableDanhSachMouseClicked
        
        int selectedRow = tableDanhSach.getSelectedRow(); // Lấy hàng được chọn
        if (selectedRow >= 0) {
            try {
                // Lấy giá trị từ bảng, kiểm tra null trước khi dùng
                Object orderIdObj = tableDanhSach.getValueAt(selectedRow, 0);
                Object orderDateObj = tableDanhSach.getValueAt(selectedRow, 1);
                Object cashierNameObj = tableDanhSach.getValueAt(selectedRow, 2);
                Object zoneObj = tableDanhSach.getValueAt(selectedRow, 3);
                Object tableNumberObj = tableDanhSach.getValueAt(selectedRow, 4);
                Object statusObj = tableDanhSach.getValueAt(selectedRow, 5);
                Object noteObj = tableDanhSach.getValueAt(selectedRow, 6);

                // Chuyển đổi giá trị sang kiểu phù hợp
                int orderId = 0;
                if (orderIdObj instanceof Integer) {
                    orderId = (Integer) orderIdObj;
                } else if (orderIdObj instanceof String) {
                    orderId = Integer.parseInt((String) orderIdObj);
                }
                
                String orderDate = (orderDateObj != null) ? orderDateObj.toString() : "";
                String cashierName = (cashierNameObj != null) ? cashierNameObj.toString() : "";
                String zone = (zoneObj != null) ? zoneObj.toString() : "";
                String tableNumber = (tableNumberObj != null) ? tableNumberObj.toString() : "";
                String status = (statusObj != null) ? statusObj.toString() : "";
                String note = (noteObj != null) ? noteObj.toString() : "";

                // Chuyển trạng thái sang tiếng Việt
                status = StatusConverter.convertStatus(status);
                String Status;
                switch (status) {
                    case "pending":
                        Status = "Đang Chờ";
                        break;
                    case "processing":
                        Status = "Đang Xử Lý";
                        break;
                    case "cooking":
                        Status = "Đang Chế Biến";
                        break;
                    case "completed":
                        Status = "Đã Hoàn Thành";
                        break;
                    case "canceled":
                        Status = "Hủy";
                        break;
                    default:
                        Status = "Không Xác Định";
                        break;
                    
                }
                maThamChieu = orderId;
                // Hiển thị dữ liệu lên giao diện
                lblKhuVuc.setText(zone);
                lblThoiGian.setText(orderDate);
                lblThuNgan.setText(cashierName);
                lblBan.setText(tableNumber);
                txtNote.setText(note);
                cboTrangThai.setSelectedItem(Status);
            } catch (NumberFormatException e) {
                System.err.println("Lỗi chuyển đổi số: " + e.getMessage());
            } catch (Exception e) {
                System.err.println("Lỗi xử lý dữ liệu: " + e.getMessage());
            }
        }

    }//GEN-LAST:event_tableDanhSachMouseClicked


