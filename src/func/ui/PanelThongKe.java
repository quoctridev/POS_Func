    private void hienThiBieuDo() {
        String luaChon = (String) cboThongKe.getSelectedItem();

        // Lấy dữ liệu dựa trên lựa chọn
        CategoryDataset dataset = switch (luaChon) {
            case "Ngày" ->
                ThongKeDAO.getRevenueDataset("day");
            case "Tuần" ->
                ThongKeDAO.getRevenueDataset("week");
            case "Tháng" ->
                ThongKeDAO.getRevenueDataset("month");
            default ->
                ThongKeDAO.getRevenueDataset("year");
        };

        // Tạo biểu đồ
        JFreeChart chart = ChartFactory.createBarChart(
                "Thống kê doanh thu",
                luaChon, "Doanh thu (VNĐ)", dataset
        );

        // Tuỳ chỉnh biểu đồ
        CategoryPlot plot = chart.getCategoryPlot();
        plot.setBackgroundPaint(Color.WHITE);
        plot.setRangeGridlinePaint(Color.GRAY);
        plot.setOutlineVisible(false);

        // Tuỳ chỉnh thanh Bar
        BarRenderer renderer = (BarRenderer) plot.getRenderer();
        for (int i = 0; i < dataset.getRowCount(); i++) {
            String rowKey = (String) dataset.getRowKey(i);
            if (rowKey.equals("Đơn hoàn thành")) {
                renderer.setSeriesPaint(i, new Color(52, 152, 219)); // Xanh - Hoàn thành
            } else if (rowKey.equals("Đơn bị huỷ")) {
                renderer.setSeriesPaint(i, new Color(231, 76, 60));  // Đỏ - Bị huỷ
            }
        }
        renderer.setBarPainter(new StandardBarPainter());

        // Tạo ChartPanel
        ChartPanel chartPanel = new ChartPanel(chart);
        chartPanel.setPreferredSize(new Dimension(981, 409));
        chartPanel.addChartMouseListener(new ChartMouseListener() {
            @Override
            public void chartMouseClicked(ChartMouseEvent event) {
                ChartEntity entity = event.getEntity();
                if (entity instanceof CategoryItemEntity categoryEntity) {
                    String selectedDate = categoryEntity.getColumnKey().toString();

                    // Xác định kiểu thống kê
                    String luaChon = (String) cboThongKe.getSelectedItem();
                    String type = switch (luaChon) {
                        case "Ngày" ->
                            "day";
                        case "Tuần" ->
                            "week";
                        case "Tháng" ->
                            "month";
                        default ->
                            "year";
                    };

                    // Hiển thị lựa chọn biểu đồ khi chọn "Ngày"
                    if (type.equals("day")) {
                        String[] options = {"Phương thức thanh toán trong ngày", "Xem doanh thu theo ca"};
                        int choice = JOptionPane.showOptionDialog(
                                SwingUtilities.getWindowAncestor(chartPanel),
                                "Chọn loại biểu đồ bạn muốn hiển thị",
                                "Chọn biểu đồ",
                                JOptionPane.DEFAULT_OPTION,
                                JOptionPane.QUESTION_MESSAGE,
                                null,
                                options,
                                options[0]
                        );

                        if (choice == 0) {
                            hienThiPieChart(selectedDate, type);
                        } else if (choice == 1) {
                            hienThiBieuDoTheoCa(selectedDate);
                        }
                    } else {
                        System.out.println(selectedDate);
                        hienThiPieChart(selectedDate, type);
                    }
                }
            }

            @Override
            public void chartMouseMoved(ChartMouseEvent event) {
            }
        });

        // Hiển thị biểu đồ
        pnDoanhThu.removeAll();
        pnDoanhThu.setLayout(new BorderLayout());
        pnDoanhThu.add(chartPanel, BorderLayout.CENTER);
        pnDoanhThu.revalidate();
        pnDoanhThu.repaint();
    }

    private void hienThiPieChart(String selectedDate, String type) {
        DefaultPieDataset dataset = ThongKeDAO.getRevenueByPaymentMethod(selectedDate, type);

        if (dataset.getItemCount() == 0) {
            JOptionPane.showMessageDialog(null, "Không có dữ liệu để hiển thị biểu đồ!", "Thông báo", JOptionPane.WARNING_MESSAGE);
            return;
        }

        JFreeChart pieChart = ChartFactory.createPieChart(
                "Phương thức thanh toán - " + selectedDate,
                dataset, true, true, false);

        PiePlot plot = (PiePlot) pieChart.getPlot();
        plot.setBackgroundPaint(Color.WHITE);
        plot.setOutlineVisible(false);

        // Gán màu cho từng phần tử dựa trên loại thanh toán
        for (Object obj : dataset.getKeys()) {
            Comparable<?> key = (Comparable<?>) obj;
            String label = key.toString();  // Lấy nhãn

            if (label.startsWith("Tiền mặt (Hoàn thành)")) {
                plot.setSectionPaint(label, new Color(46, 204, 113));  // Xanh lá
            } else if (label.startsWith("QR-Code (Hoàn thành)")) {
                plot.setSectionPaint(label, new Color(241, 196, 15));  // Vàng
            } else if (label.startsWith("QR-Code (Đơn huỷ)")) {
                plot.setSectionPaint(label, new Color(231, 76, 60));  // Đỏ
            } else {
                plot.setSectionPaint(label, new Color(52, 152, 219));  // Màu xanh dương mặc định
            }
        }

        ChartPanel pieChartPanel = new ChartPanel(pieChart);
        pieChartPanel.setPreferredSize(new Dimension(500, 400));

        JDialog dialog = new JDialog((Frame) SwingUtilities.getWindowAncestor(this), "Thống kê phương thức thanh toán", true);
        dialog.setLayout(new BorderLayout());
        dialog.add(pieChartPanel, BorderLayout.CENTER);
        dialog.pack();
        dialog.setLocationRelativeTo(null);
        dialog.setVisible(true);
    }

    private void hienThiBieuDoTheoCa(String date) {
        CategoryDataset dataset = ThongKeDAO.getRevenueByShift(date);

        JFreeChart chart = ChartFactory.createBarChart(
                "Thống kê doanh thu theo ca làm (" + date + ")",
                "Ca làm", "Giá trị", dataset
        );

        // Tuỳ chỉnh biểu đồ
        CategoryPlot plot = chart.getCategoryPlot();
        plot.setBackgroundPaint(Color.WHITE);
        plot.setRangeGridlinePaint(Color.GRAY);
        plot.setOutlineVisible(false);

        // Tuỳ chỉnh thanh Bar
        BarRenderer renderer = (BarRenderer) plot.getRenderer();
        for (int i = 0; i < dataset.getRowCount(); i++) {
            String rowKey = dataset.getRowKey(i).toString().trim(); // Đảm bảo không có khoảng trắng thừa

            if (rowKey.equalsIgnoreCase("Doanh thu")) {
                renderer.setSeriesPaint(i, new Color(52, 152, 219)); // Xanh - Doanh thu
            } else if (rowKey.equalsIgnoreCase("Đơn bị huỷ")) {
                renderer.setSeriesPaint(i, new Color(231, 76, 60));  // Đỏ - Đơn bị hủy
            }
        }
        renderer.setBarPainter(new StandardBarPainter());

        // Hiển thị biểu đồ trong popup
        JDialog dialog = new JDialog((Frame) SwingUtilities.getWindowAncestor(this), "Chi tiết doanh thu theo ca", true);
        dialog.setSize(600, 400);
        dialog.setLocationRelativeTo(this);
        dialog.setLayout(new BorderLayout());
        dialog.add(new ChartPanel(chart), BorderLayout.CENTER);
        dialog.setVisible(true);
    }
