    private void selectPayment(JLabel selected) {
        if (selectedPayment != null) {
            selectedPayment.setBackground(new Color(221, 221, 221)); // Reset màu của cái trước
        }
        selected.setBackground(new Color(152, 178, 230)); // Màu xanh khi chọn
        selectedPayment = selected; // Cập nhật lựa chọn hiện tại
    }

    private int getSelectedPayment() {
        if (selectedPayment == lbTienMat) {
            return 1;
        } else if (selectedPayment == lbChuyenKhoan) {
            return 2;
        }
        return 0;
    }

